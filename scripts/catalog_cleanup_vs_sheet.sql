-- Normalizer: digits only, leading zeros stripped, Excel '.0' handled
CREATE OR REPLACE FUNCTION pg_temp.norm_upc(t text) RETURNS text AS $$
  SELECT ltrim(regexp_replace(regexp_replace(coalesce(t,''), '\.0+$', ''), '\D', '', 'g'), '0');
$$ LANGUAGE sql IMMUTABLE;

CREATE OR REPLACE FUNCTION pg_temp.norm_txt(t text) RETURNS text AS $$
  SELECT upper(regexp_replace(trim(coalesce(t,'')), '\s+', ' ', 'g'));
$$ LANGUAGE sql IMMUTABLE;

-- ============================================================
-- AUDIT 1 — duplicate products on the site (same name, still active)
-- ============================================================
SELECT pg_temp.norm_txt(description) AS name,
       count(*) AS copies,
       array_agg(id ORDER BY created_at) AS ids,
       array_agg(concat_ws(' | ', pkg_size, uom, price::text) ORDER BY created_at) AS variants
FROM products
WHERE is_active
GROUP BY 1 HAVING count(*) > 1
ORDER BY copies DESC, name;

-- ============================================================
-- AUDIT 2 — active products NOT in Jen's sheet
-- (no UPC match AND no name+pack match — e.g. the $0.59 EACH bananas)
-- ============================================================
SELECT p.id, p.category, p.description, p.pkg_size, p.uom, p.price, p.upc, p.created_at
FROM products p
WHERE p.is_active
  AND NOT EXISTS (SELECT 1 FROM _sheet s
                  WHERE pg_temp.norm_upc(s.upc) <> ''
                    AND pg_temp.norm_upc(s.upc) = pg_temp.norm_upc(p.upc))
  AND NOT EXISTS (SELECT 1 FROM _sheet s
                  WHERE s.descr = pg_temp.norm_txt(p.description)
                    AND pg_temp.norm_txt(s.pkg) = pg_temp.norm_txt(p.pkg_size))
ORDER BY p.category, p.description;

-- ============================================================
-- AUDIT 3 — sheet rows that never made it onto the site
-- ============================================================
SELECT s.*
FROM (SELECT DISTINCT ON (descr, pkg) * FROM _sheet ORDER BY descr, pkg) s
WHERE NOT EXISTS (SELECT 1 FROM products p
                  WHERE pg_temp.norm_upc(p.upc) <> ''
                    AND pg_temp.norm_upc(p.upc) = pg_temp.norm_upc(s.upc))
  AND NOT EXISTS (SELECT 1 FROM products p
                  WHERE pg_temp.norm_txt(p.description) = s.descr)
ORDER BY s.descr;

-- ============================================================
-- CLEANUP — run after reviewing the audits above
-- ============================================================
BEGIN;

-- C1: For duplicate names, keep the copy that best matches the sheet
-- (matching pack+price ranks first, then oldest); deactivate the rest.
WITH ranked AS (
  SELECT p.id,
         row_number() OVER (
           PARTITION BY pg_temp.norm_txt(p.description)
           ORDER BY
             (EXISTS (SELECT 1 FROM _sheet s
                      WHERE s.descr = pg_temp.norm_txt(p.description)
                        AND pg_temp.norm_txt(s.pkg) = pg_temp.norm_txt(p.pkg_size)
                        AND s.price = p.price)) DESC,
             (EXISTS (SELECT 1 FROM _sheet s
                      WHERE pg_temp.norm_upc(s.upc) <> ''
                        AND pg_temp.norm_upc(s.upc) = pg_temp.norm_upc(p.upc))) DESC,
             p.created_at ASC
         ) AS rn
  FROM products p
  WHERE p.is_active
)
UPDATE products SET is_active = false
WHERE id IN (SELECT id FROM ranked WHERE rn > 1);

-- C2: Deactivate active products that aren't in the sheet at all
-- (review AUDIT 2 first — re-activate any you added on purpose)
UPDATE products p SET is_active = false
WHERE p.is_active
  AND NOT EXISTS (SELECT 1 FROM _sheet s
                  WHERE pg_temp.norm_upc(s.upc) <> ''
                    AND pg_temp.norm_upc(s.upc) = pg_temp.norm_upc(p.upc))
  AND NOT EXISTS (SELECT 1 FROM _sheet s
                  WHERE s.descr = pg_temp.norm_txt(p.description)
                    AND pg_temp.norm_txt(s.pkg) = pg_temp.norm_txt(p.pkg_size));

-- Sanity check before committing:
SELECT count(*) FILTER (WHERE is_active) AS active_after,
       count(*) FILTER (WHERE NOT is_active) AS inactive_after
FROM products;

COMMIT;
